"""
This class serves as the core unification component for monomer binder
structural predictions generated by multiple prediction methods. It loads
structure files from different modeling pipelines, extracts standardized
metadata from each individual binder model, and organizes the predictions into
a unified dataset that can be used for downstream comparative analyses.

This monomer-binder version is adapted from the original complex/multimer
version. The original script identified both target and binder chains. In this
version, target-related logic has been removed because each structure should
represent the binder monomer only.

Overall flow:
    -> method parsing
    -> structure loading
    -> binder chain identification
    -> binder sequence extraction
    -> score / metadata extraction
    -> rank assignment
    -> unified dataset compilation
"""

from pathlib import Path
from joblib import Parallel, delayed
from dataclasses import dataclass, asdict
from Bio.PDB import PDBParser, MMCIFParser
from Bio.Data.IUPACData import protein_letters_3to1
import pandas as pd
import re
import json
import pickle
import numpy as np
import gemmi
import tempfile


@dataclass
class StructureRecord:
    path: Path
    file_type: str      # ".pdb" or ".cif"
    method: str         # prediction method name

    complex_name: str | None = None      # kept for compatibility; usually binder/input name
    prediction_id: str | None = None     # prediction/model id
    rank: int | None = None              # model rank if available

    binder_chain_id: str | None = None
    binder_length: int | None = None
    binder_sequence: str | None = None

    score: float | None = None
    score_name: str | None = None        # e.g. "ranking_score", "aggregate_score"
    json_path: Path | None = None
    pkl_path: Path | None = None
    npz_path: Path | None = None

    parse_success: bool = True
    error_message: str | None = None


class PredictionDataset:
    """
    Part 1:
    Setup and file discovery
    """

    def __init__(self, root_dir):
        self.root_dir = Path(root_dir)
        self.records = []

    def detect_method(self, path):
        path = Path(path)
        relative_parts = path.relative_to(self.root_dir).parts
        method_folder = relative_parts[0]

        known_methods = {
            "AF2": "AF2",
            "AF3": "AF3",
            "Boltz-2": "Boltz-2",
            "Chai-1": "Chai-1",
            "HelixFold3": "HelixFold3",
            "OF2": "OF2",
            "OF3": "OF3",
            "Protenix": "Protenix",
            "SeedFold": "SeedFold",
        }

        return known_methods.get(method_folder, "unknown")

    def should_keep_structure_file(self, path):
        """
        Return True only for structure files that should be included in the dataset.
        Adjust filename/path rules here to match your monomer prediction directory layout.
        """
        path = Path(path)
        method = self.detect_method(path)

        stem = path.stem.lower()
        parent = path.parent.name.lower()
        parts_lower = [p.lower() for p in path.parts]

        if not path.is_file():
            return False

        if path.suffix.lower() not in {".pdb", ".cif"}:
            return False

        # AF2 often contains ranked_*.pdb plus relaxed/unrelaxed files.
        # Keep only ranked files to avoid duplicates.
        if method == "AF2":
            if stem.startswith("ranked_"):
                return True

            if "unrelaxed" in stem or "relaxed" in stem:
                return False

            return False

        # HelixFold3 output is commonly organized in rank folders.
        if method == "HelixFold3":
            if any("rank" in part for part in parts_lower):
                return True
            return False

        # AF3 often stores one prediction per seed folder.
        # This preserves your original seed-0-only logic.
        if method == "AF3":
            parent = path.parent.name.lower()
            if parent.startswith("seed-0"):
                return True
            return False

        # OF2
        if method == "OF2":
            if "relaxed" in stem and "unrelaxed" not in stem:
                return True

            return False

        return True

    def find_structure_files(self):
        all_files = list(self.root_dir.rglob("*.pdb")) + list(self.root_dir.rglob("*.cif"))
        files = [f for f in all_files if self.should_keep_structure_file(f)]
        return sorted(files)

    """
    Part 2:
    Structure parsing
    """

    def _cif_to_tmp_pdb(self, cif_path: Path) -> str:
        doc = gemmi.cif.read_file(str(cif_path))
        structure = gemmi.make_structure_from_block(doc.sole_block())

        tmp = tempfile.NamedTemporaryFile(suffix=".pdb", delete=False)
        structure.write_pdb(tmp.name)
        tmp.close()
        return tmp.name

    def load_structure(self, path):
        path = Path(path)
        method = self.detect_method(path)

        if path.suffix.lower() == ".pdb":
            parser = PDBParser(QUIET=True)
            return parser.get_structure(path.stem, str(path))

        if path.suffix.lower() == ".cif":
            # Keeping your original OF3 conversion workaround.
            if method == "OF3":
                tmp_pdb = self._cif_to_tmp_pdb(path)
                parser = PDBParser(QUIET=True)
                return parser.get_structure(path.stem, tmp_pdb)

            parser = MMCIFParser(QUIET=True)
            return parser.get_structure(path.stem, str(path))

        raise ValueError(f"Unsupported structure file type: {path}")

    def get_chain_lengths(self, structure):
        chain_lengths = {}

        for chain in structure.get_chains():
            residues = [res for res in chain.get_residues() if res.id[0] == " "]
            chain_lengths[chain.id] = len(residues)

        return chain_lengths

    def extract_chain_sequence(self, chain):
        sequence = []

        for residue in chain.get_residues():
            if residue.id[0] != " ":
                continue

            resname = residue.resname.title()
            one_letter = protein_letters_3to1.get(resname, "X")
            sequence.append(one_letter)

        return "".join(sequence)

    """
    Part 3:
    Metadata matching and score extraction
    Model specific
    """

    def extract_ranking_info_for_structure(self, path: Path, method: str) -> dict:
        extractors = {
            "SeedFold": self._extract_seedfold_ranking_info,
            "Protenix": self._extract_protenix_ranking_info,
            "OF2": self._extract_of2_ranking_info,
            "OF3": self._extract_of3_ranking_info,
            "HelixFold3": self._extract_helixfold3_ranking_info,
            "Chai-1": self._extract_chai1_ranking_info,
            "Boltz-2": self._extract_boltz2_ranking_info,
            "AF3": self._extract_af3_ranking_info,
            "AF2": self._extract_af2_ranking_info,
        }

        extractor = extractors.get(method, self._extract_default_ranking_info)
        return extractor(path)

    def _load_json(self, path: Path):
        with open(path, "r") as f:
            return json.load(f)

    def _load_pkl(self, path: Path):
        with open(path, "rb") as f:
            return pickle.load(f)

    def _load_npz(self, path: Path):
        return dict(np.load(path, allow_pickle=True))

    def _safe_float(self, value):
        try:
            return float(value)
        except Exception:
            return None

    # SeedFold

    def _extract_seedfold_ranking_info(self, path: Path) -> dict:
        stem = path.stem
        json_path = path.with_name(f"confidence_{stem}.json")

        score = None
        if json_path.exists():
            data = self._load_json(json_path)
            score = self._safe_float(data.get("confidence_score"))

        return {
            "prediction_id": stem,
            "score": score,
            "score_name": "confidence_score" if score is not None else None,
            "json_path": json_path if json_path.exists() else None,
            "pkl_path": None,
            "npz_path": None,
        }

    # Protenix

    def _extract_protenix_ranking_info(self, path: Path) -> dict:
        stem = path.stem
        json_path = None

        m = re.match(r"(.+)_sample_(\d+)$", stem)
        if m:
            prefix, sample_id = m.groups()
            json_path = path.with_name(f"{prefix}_summary_confidence_sample_{sample_id}.json")

        score = None
        if json_path and json_path.exists():
            data = self._load_json(json_path)
            score = self._safe_float(data.get("ranking_score"))

        return {
            "prediction_id": stem,
            "score": score,
            "score_name": "ranking_score" if score is not None else None,
            "json_path": json_path if (json_path and json_path.exists()) else None,
            "pkl_path": None,
            "npz_path": None,
        }

    # OF2

    def _extract_of2_ranking_info(self, path: Path) -> dict:
        return {
            "prediction_id": path.stem,
            "score": None,
            "score_name": None,
            "json_path": None,
            "pkl_path": None,
            "npz_path": None,
        }

    # OF3

    def _extract_of3_ranking_info(self, path: Path) -> dict:
        stem = path.stem
        json_path = None

        if stem.endswith("_model"):
            json_path = path.with_name(f"{stem[:-6]}_confidences_aggregated.json")

        score = None
        if json_path and json_path.exists():
            data = self._load_json(json_path)
            score = self._safe_float(data.get("sample_ranking_score"))

        return {
            "prediction_id": stem,
            "score": score,
            "score_name": "sample_ranking_score" if score is not None else None,
            "json_path": json_path if (json_path and json_path.exists()) else None,
            "pkl_path": None,
            "npz_path": None,
        }

    # HelixFold3

    def _extract_helixfold3_ranking_info(self, path: Path) -> dict:
        folder_name = path.parent.name
        m = re.search(r"rank(\d+)$", folder_name.lower())

        score = None
        if m:
            rank_num = int(m.group(1))
            score = -rank_num

        return {
            "prediction_id": folder_name,
            "score": score,
            "score_name": "folder_rank" if score is not None else None,
            "json_path": path.with_name("all_results.json") if path.with_name("all_results.json").exists() else None,
            "pkl_path": None,
            "npz_path": None,
        }

    # Chai-1

    def _extract_chai1_ranking_info(self, path: Path) -> dict:
        stem = path.stem
        suffix = stem.replace("pred.", "")
        npz_path = path.with_name(f"scores.{suffix}.npz")

        score = None
        if npz_path.exists():
            data = np.load(npz_path, allow_pickle=True)
            if "aggregate_score" in data:
                value = data["aggregate_score"]
                if np.size(value) == 1:
                    score = self._safe_float(np.array(value).item())

        return {
            "prediction_id": stem,
            "score": score,
            "score_name": "aggregate_score" if score is not None else None,
            "json_path": None,
            "pkl_path": None,
            "npz_path": npz_path if npz_path.exists() else None,
        }

    # Boltz-2

    def _extract_boltz2_ranking_info(self, path: Path) -> dict:
        json_candidates = sorted(path.parent.glob("*.json"))
        json_path = json_candidates[0] if json_candidates else None

        score = None
        if json_path and json_path.exists():
            data = self._load_json(json_path)
            score = self._safe_float(data.get("confidence_score"))

        return {
            "prediction_id": path.stem,
            "score": score,
            "score_name": "confidence_score" if score is not None else None,
            "json_path": json_path,
            "pkl_path": None,
            "npz_path": None,
        }

    # AF3

    def _extract_af3_ranking_info(self, path: Path) -> dict:
        json_files = sorted(path.parent.glob("*.json"))

        summary_json = None
        for jf in json_files:
            if "summary" in jf.name.lower():
                summary_json = jf
                break

        score = None
        if summary_json and summary_json.exists():
            data = self._load_json(summary_json)
            score = self._safe_float(data.get("ranking_score"))

        return {
            "prediction_id": path.parent.name,
            "score": score,
            "score_name": "ranking_score" if score is not None else None,
            "json_path": summary_json,
            "pkl_path": None,
            "npz_path": None,
        }

    # AF2

    def _extract_af2_ranking_info(self, path: Path):
        parent = path.parent
        ranking_json = parent / "ranking_debug.json"

        prediction_id = path.stem  # e.g. ranked_0
        score = None
        pkl_path = None

        rank_idx = None
        m = re.match(r"ranked_(\d+)$", path.stem.lower())
        
        model_name = None

        if m:
            rank_idx = int(m.group(1))

        model_name = None

        if ranking_json.exists():
            data = self._load_json(ranking_json)

            if rank_idx is not None and "order" in data and isinstance(data["order"], list):
                if rank_idx < len(data["order"]):
                    model_name = data["order"][rank_idx]
            

            if model_name and "iptm+ptm" in data and isinstance(data["iptm+ptm"], dict):
                score = self._safe_float(data["iptm+ptm"].get(model_name))
            
            if model_name:
                candidate_pkl = parent / f"result_{model_name}.pkl"
                if candidate_pkl.exists():
                    pkl_path = candidate_pkl
            
        return {
            "prediction_id": model_name or prediction_id,
            "score": score,
            "score_name": "iptm+ptm" if score is not None else None,
            "json_path": ranking_json if ranking_json.exists() else None,
            "pkl_path": pkl_path,
            "npz_path": None,
        }

    def extract_complex_name(self, path: Path, method: str):
        """
        Kept as complex_name for compatibility with your downstream code.
        For monomer predictions, this should usually be interpreted as the
        binder/input name rather than a complex name.
        """
        rel = path.relative_to(self.root_dir)
        parts = rel.parts

        if method == "HelixFold3":
            return parts[1] if len(parts) > 1 else path.parent.name

        if len(parts) >= 2:
            return parts[1]

        return path.parent.name

    def _extract_default_ranking_info(self, path: Path) -> dict:
        return {
            "prediction_id": path.stem,
            "score": None,
            "score_name": None,
            "json_path": None,
            "pkl_path": None,
            "npz_path": None,
        }

    """
    Record Builder
    """

    def extract_record(self, path):
        path = Path(path)
        method = "unknown"

        try:
            method = self.detect_method(path)
            file_type = path.suffix.lower()
            structure = self.load_structure(path)
            binder_chain = next(structure.get_chains())

            binder_chain_id = binder_chain.id
            binder_sequence = self.extract_chain_sequence(binder_chain)
            binder_length = len(binder_sequence)

            complex_name = self.extract_complex_name(path, method)
            ranking = self.extract_ranking_info_for_structure(path, method)

            return StructureRecord(
                path=path,
                file_type=file_type,
                method=method,
                complex_name=complex_name,
                prediction_id=ranking.get("prediction_id"),
                score=ranking.get("score"),
                score_name=ranking.get("score_name"),
                json_path=ranking.get("json_path"),
                pkl_path=ranking.get("pkl_path"),
                npz_path=ranking.get("npz_path"),
                binder_chain_id=binder_chain_id,
                binder_length=binder_length,
                binder_sequence=binder_sequence,
                parse_success=True,
                error_message=None,
            )

        except Exception as e:
            return StructureRecord(
                path=path,
                file_type=path.suffix.lower(),
                method=method,
                parse_success=False,
                error_message=str(e),
            )

    """
    Dataset-level logic
    """

    def load_all_records(self, n_jobs=-2, verbose=10):
        files = self.find_structure_files()

        records = Parallel(n_jobs=n_jobs, verbose=verbose)(
            delayed(self.extract_record)(path) for path in files
        )

        self.records = records
        return self.records

    def assign_ranks(self):
        groups = {}

        for record in self.records:
            key = (record.method, record.complex_name)
            groups.setdefault(key, []).append(record)

        for (method, _), group in groups.items():
            # AF2
            if method == "AF2":
                def af2_rank_key(record):
                    stem = Path(record.path).stem.lower()
                    m = re.match(r"ranked_(\d+)$", stem)
                    return int(m.group(1)) if m else 999

                group.sort(key=af2_rank_key)
                for i, rec in enumerate(group, start=1):
                    rec.rank = i
                continue

            # Other methods
            scored = [r for r in group if r.score is not None]
            unscored = [r for r in group if r.score is None]

            scored.sort(key=lambda r: r.score, reverse=True)

            for i, rec in enumerate(scored, start=1):
                rec.rank = i

            if not scored and len(group) == 1:
                group[0].rank = 1
            else:
                for rec in unscored:
                    rec.rank = None

    def to_dataframe(self):
        df = pd.DataFrame([asdict(record) for record in self.records])

        for col in df.columns:
            df[col] = df[col].apply(lambda x: str(x) if isinstance(x, Path) else x)

        return df

    def save_parquet(self, output_path):
        df = self.to_dataframe()
        output_path = Path(output_path)
        df.to_parquet(output_path, index=False)


