def cif_to_tmp_pdb(cif_path):
    cif_path = Path(cif_path)

    doc = gemmi.cif.read_file(str(cif_path))
    structure = gemmi.make_structure_from_block(doc.sole_block())

    tmp = tempfile.NamedTemporaryFile(suffix=".pdb", delete=False)
    structure.write_pdb(tmp.name)
    tmp.close()
    return tmp.name

def load_structure_biopython(path, file_type=None, structure_id=None):
    path = Path(path)

    if structure_id is None:
        structure_id = path.stem

    if file_type is None:
        suffix = path.suffix.lower()
        if suffix == ".pdb":
            file_type = "pdb"
        elif suffix == ".cif":
            file_type == "cif"
        else:
            raise ValueError(f"Could not infer file type from suffix: {path}")
        
    file_type = str(file_type).lower().strip().lstrip(".")

    if file_type == "pdb":
        parser = PDBParser(QUIET=True)
        return parser.get_structure(structure_id, str(path))

    elif file_type in {"cif", "mmcif"}:
        try:
            parser = MMCIFParser(QUIET=True)
            return parser.get_structure(structure_id, str(path))
        except Exception:
            tmp_pdb = cif_to_tmp_pdb(path)
            try:
                parser = PDBParser(QUIET=True)
                return parser.get_structure(structure_id, tmp_pdb)
            finally:
                if os.path.exists(tmp_pdb):
                    os.unlink(tmp_pdb)

    else:
        raise ValueError(f"Unsupported file type: {file_type}")

def get_chain_by_id(structure, chain_id):
    for model in structure:
        for chain in model:
            if chain.id == chain_id:
                return chain
    
    available = []
    for model in structure:
        available.extend([chain.id for chain in model])

    raise KeyError(f"Chain '{chain_id}' not found. Available chains: {sorted(set(available))}")

def extract_protein_ca_atoms(chain):
    ca_atoms = []

    for residue in chain:
        if residue.id[0] != " ":
            continue

        if not is_aa(residue, standard=False):
            continue

        if "CA" in residue:
            ca_atoms.append(residue["CA"])

    return ca_atoms

def compute_binder_ca_rmsd_aligned_on_binder(path_1, path_2, binder_chain_1, binder_chain_2, file_type_1=None, file_type_2=None):
    try:
        structure_1 = load_structure_biopython(path_1, file_type=file_type_1, structure_id="ref")
        structure_2 = load_structure_biopython(path_2, file_type=file_type_2, structure_id="mov")

        chain_1 = get_chain_by_id(structure_1, binder_chain_1)
        chain_2 = get_chain_by_id(structure_2, binder_chain_2)

        ca_atoms_1 = extract_protein_ca_atoms(chain_1)
        ca_atoms_2 = extract_protein_ca_atoms(chain_2)

        len_1 = len(ca_atoms_1)
        len_2 = len(ca_atoms_2)

        if len_1 == 0 or len_2 == 0:
            return {
                "binder_ca_rmsd_align_binder": np.nan,
                "n_ca_aligned": 0,
                "binder_len_1": len_1,
                "binder_len_2": len_2,
                "status": "failed",
                "error": "One or both binder chains have no CA atoms."                
            }
        
        if len_1 != len_2:
            return {
                "binder_ca_rmsd_align_binder": np.nan,
                "n_ca_aligned": min(len_1, len_2),
                "binder_len_1": len_1,
                "binder_len_2": len_2,
                "status": "failed",
                "error": (
                    f"Binder CA atom counts differ: {len_1} vs {len_2}. "
                    "Cannot safely superimpose by one-to-one residue order."
                )                
            }
        
        sup = Superimposer()
        sup.set_atoms(ca_atoms_1, ca_atoms_2)

        return {
            "binder_ca_rmsd_align_binder": float(sup.rms),
            "n_ca_aligned": len_1,
            "binder_len_1": len_1,
            "binder_len_2": len_2,
            "status": "ok",
            "error": None         
        }
    
    except Exception as e:
        return {
            "binder_ca_rmsd_align_binder": np.nan,
            "n_ca_aligned": 0,
            "binder_len_1": np.nan,
            "binder_len_2": np.nan,
            "status": "failed",
            "error": str(e)            
        }

def compute_binder_ca_rmsd_for_row(row):
    return compute_binder_ca_rmsd_aligned_on_binder(
        path_1=row["structure_path_1"],
        path_2=row["structure_path_2"],
        binder_chain_1=row["binder_chain_1"],
        binder_chain_2=row["binder_chain_2"],
        file_type_1=row.get("file_type_1"),
        file_type_2=row.get("file_type_2"),
    )

