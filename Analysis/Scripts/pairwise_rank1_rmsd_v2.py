def get_protein_residues(chain):
    residues = []
    for residue in chain:
        if residue.id[0] != " ":
            continue
        if not is_aa(residue, standard=False):
            continue
        residues.append(residue)
    return residues

def residue_key(residue, mode="id"):
    """
    Key used to match target residues between structures.

    ``mode="id"`` matches by residue number and insertion code.
    ``mode="position"`` matches by zero-based protein-residue position.
    """
    if mode == "id":
        return (int(residue.id[1]), residue.id[2].strip())
    raise ValueError(f"Unsupported residue key mode: {mode}")

def get_residue_dict_by_key(chain, mode="id"):
    residues = get_protein_residues(chain)
    if mode == "position":
        return {i: res for i, res in enumerate(residues)}
    return {residue_key(res, mode=mode): res for res in residues}

def get_target_interface_residue_keys(
    target_chain,
    binder_chain,
    cutoff=5.0,
    residue_match_mode="id",
):
    """
    Return target residue keys whose atoms are within ``cutoff`` Angstrom of
    any binder atom.
    """
    target_residues = get_protein_residues(target_chain)
    binder_atoms = [
        atom
        for residue in get_protein_residues(binder_chain)
        for atom in residue.get_atoms()
    ]

    if not binder_atoms:
        return []

    ns = NeighborSearch(binder_atoms)
    interface_keys = []

    for position, residue in enumerate(target_residues):
        key = position if residue_match_mode == "position" else residue_key(
            residue, mode=residue_match_mode
        )
        for atom in residue.get_atoms():
            if ns.search(atom.coord, cutoff):
                interface_keys.append(key)
                break

    return interface_keys

def get_target_shell_residues(target_chain, binder_chain, cutoff=5.0):
    target_residues = get_protein_residues(target_chain)
    binder_atoms = [
        atom
        for residue in get_protein_residues(binder_chain)
        for atom in residue.get_atoms()
    ]

    if not binder_atoms:
        return []

    ns = NeighborSearch(binder_atoms)
    shell_residues = []

    for residue in target_residues:
        for atom in residue.get_atoms():
            if ns.search(atom.coord, cutoff):
                shell_residues.append(residue)
                break
    # this is the list of resiudes in the interface of the target
    return shell_residues

def get_residue_position_dict(chain):
    residues = get_protein_residues(chain)
    return {res: i for i, res in enumerate(residues)}


def get_residue_dict_by_position(chain):
    residues = get_protein_residues(chain)
    return {i: res for i, res in enumerate(residues)}

def get_matched_ca_atoms_from_residue_keys(
    chain_1,
    chain_2,
    residue_keys,
    residue_match_mode="id",
):
    res_dict_1 = get_residue_dict_by_key(chain_1, mode=residue_match_mode)
    res_dict_2 = get_residue_dict_by_key(chain_2, mode=residue_match_mode)

    atoms_1 = []
    atoms_2 = []

    for key in residue_keys:
        res1 = res_dict_1.get(key)
        res2 = res_dict_2.get(key)

        if res1 is None or res2 is None:
            continue
        if "CA" not in res1 or "CA" not in res2:
            continue

        atoms_1.append(res1["CA"])
        atoms_2.append(res2["CA"])

    return atoms_1, atoms_2

def get_matched_ca_atoms_from_residue_positions(chain_1, chain_2, positions):
    return get_matched_ca_atoms_from_residue_keys(
        chain_1,
        chain_2,
        positions,
        residue_match_mode="position",
    )

def calc_interface_overlap(interface_keys_1, interface_keys_2):
    keys_1 = set(interface_keys_1)
    keys_2 = set(interface_keys_2)
    shared_keys = sorted(keys_1 & keys_2)

    if not keys_1 or not keys_2:
        return {
            "shared_keys": shared_keys,
            "overlap_method_1": 0.0,
            "overlap_method_2": 0.0,
            "overlap_max": 0.0,
        }

    overlap_1 = len(shared_keys) / len(keys_1)
    overlap_2 = len(shared_keys) / len(keys_2)
    return {
        "shared_keys": shared_keys,
        "overlap_method_1": float(overlap_1),
        "overlap_method_2": float(overlap_2),
        "overlap_max": float(max(overlap_1, overlap_2)),
    }

def calc_rmsd_from_atoms(atom_list_1, atom_list_2, rot, tran):
    # Apply the rotation/translation that maps structure 2 onto structure 1,
    # then compute RMSD against structure 1 coordinates.

    coords_1 = np.array([atom.coord for atom in atom_list_1], dtype=float)
    coords_2 = np.array([atom.coord for atom in atom_list_2], dtype=float)

    coords_2_transformed = np.dot(coords_2, rot) + tran

    diff = coords_1 - coords_2_transformed
    rmsd = np.sqrt(np.mean(np.sum(diff * diff, axis=1)))
    return float(rmsd)

def _failed_result(
    error,
    cutoff,
    n_interface_residues_1=np.nan,
    n_interface_residues_2=np.nan,
    n_shared_interface_residues=0,
    interface_overlap_method_1=np.nan,
    interface_overlap_method_2=np.nan,
    interface_overlap_max=np.nan,
    alignment_mode=None,
    n_alignment_residues_selected=0,
    n_alignment_ca_aligned=0,
    n_binder_ca_compared=0,
):
    return {
        "binder_ca_rmsd_pocket_align": np.nan,
        "n_shell_residues_ref": n_interface_residues_1,
        "n_shell_ca_aligned": n_alignment_ca_aligned,
        "n_binder_ca_compared": n_binder_ca_compared,
        "target_shell_cutoff": cutoff,
        "status_target_shell": "failed",
        "error_target_shell": error,
        "n_interface_residues_1": n_interface_residues_1,
        "n_interface_residues_2": n_interface_residues_2,
        "n_shared_interface_residues": n_shared_interface_residues,
        "interface_overlap_method_1": interface_overlap_method_1,
        "interface_overlap_method_2": interface_overlap_method_2,
        "interface_overlap_max": interface_overlap_max,
        "alignment_mode": alignment_mode,
        "n_alignment_residues_selected": n_alignment_residues_selected,
        "n_alignment_ca_aligned": n_alignment_ca_aligned,
    }

def compute_binder_ca_rmsd_aligned_on_target_shell(
    path_1,
    path_2,
    binder_chain_1,
    binder_chain_2,
    target_chain_1,
    target_chain_2,
    file_type_1=None,
    file_type_2=None,
    cutoff=5.0,
    overlap_threshold=0.50,
    residue_match_mode="id",
):
    try:
        structure_1 = load_structure_biopython(path_1, file_type=file_type_1, structure_id="ref")
        structure_2 = load_structure_biopython(path_2, file_type=file_type_2, structure_id="mov")

        binder_1 = get_chain_by_id(structure_1, binder_chain_1)
        binder_2 = get_chain_by_id(structure_2, binder_chain_2)
        target_1 = get_chain_by_id(structure_1, target_chain_1)
        target_2 = get_chain_by_id(structure_2, target_chain_2)

        interface_keys_1 = get_target_interface_residue_keys(
            target_chain=target_1,
            binder_chain=binder_1,
            cutoff=cutoff,
            residue_match_mode=residue_match_mode,
        )
        interface_keys_2 = get_target_interface_residue_keys(
            target_chain=target_2,
            binder_chain=binder_2,
            cutoff=cutoff,
            residue_match_mode=residue_match_mode,
        )

        n_interface_1 = len(interface_keys_1)
        n_interface_2 = len(interface_keys_2)


        if n_interface_1 == 0:
            return _failed_result(
                "No target-interface residues found in reference structure.",
                cutoff=cutoff,
                n_interface_residues_1=n_interface_1,
                n_interface_residues_2=n_interface_2,
                interface_overlap_method_1=0.0,
                interface_overlap_method_2=0.0,
                interface_overlap_max=0.0,
            )

        overlap = calc_interface_overlap(interface_keys_1, interface_keys_2)
        shared_keys = overlap["shared_keys"]
        overlap_max = overlap["overlap_max"]

        if overlap_max >= overlap_threshold:
            alignment_keys = shared_keys
            alignment_mode = "shared_interface"
        else:
            alignment_keys = interface_keys_1
            alignment_mode = "reference_interface"

        if len(alignment_keys) == 0:
            return _failed_result(
                "No target-interface residues selected for alignment.",
                cutoff=cutoff,
                n_interface_residues_1=n_interface_1,
                n_interface_residues_2=n_interface_2,
                n_shared_interface_residues=len(shared_keys),
                interface_overlap_method_1=overlap["overlap_method_1"],
                interface_overlap_method_2=overlap["overlap_method_2"],
                interface_overlap_max=overlap_max,
                alignment_mode=alignment_mode,
            )

        shell_ca_1, shell_ca_2 = get_matched_ca_atoms_from_residue_keys(
            target_1,
            target_2,
            alignment_keys,
            residue_match_mode=residue_match_mode,
        )

        if len(shell_ca_1) < 3:
            return _failed_result(
                f"Too few matched target-interface CA atoms for superposition: {len(shell_ca_1)}",
                cutoff=cutoff,
                n_interface_residues_1=n_interface_1,
                n_interface_residues_2=n_interface_2,
                n_shared_interface_residues=len(shared_keys),
                interface_overlap_method_1=overlap["overlap_method_1"],
                interface_overlap_method_2=overlap["overlap_method_2"],
                interface_overlap_max=overlap_max,
                alignment_mode=alignment_mode,
                n_alignment_residues_selected=len(alignment_keys),
                n_alignment_ca_aligned=len(shell_ca_1),
            )

        sup = Superimposer()
        sup.set_atoms(shell_ca_1, shell_ca_2)
        rot, tran = sup.rotran

        binder_ca_1 = extract_protein_ca_atoms(binder_1)
        binder_ca_2 = extract_protein_ca_atoms(binder_2)

        if len(binder_ca_1) == 0 or len(binder_ca_2) == 0:
            return _failed_result(
                "One or both binder chains have no CA atoms.",
                cutoff=cutoff,
                n_interface_residues_1=n_interface_1,
                n_interface_residues_2=n_interface_2,
                n_shared_interface_residues=len(shared_keys),
                interface_overlap_method_1=overlap["overlap_method_1"],
                interface_overlap_method_2=overlap["overlap_method_2"],
                interface_overlap_max=overlap_max,
                alignment_mode=alignment_mode,
                n_alignment_residues_selected=len(alignment_keys),
                n_alignment_ca_aligned=len(shell_ca_1),
            )

        if len(binder_ca_1) != len(binder_ca_2):
            return _failed_result(
                f"Binder CA atom counts differ: {len(binder_ca_1)} vs {len(binder_ca_2)}",
                cutoff=cutoff,
                n_interface_residues_1=n_interface_1,
                n_interface_residues_2=n_interface_2,
                n_shared_interface_residues=len(shared_keys),
                interface_overlap_method_1=overlap["overlap_method_1"],
                interface_overlap_method_2=overlap["overlap_method_2"],
                interface_overlap_max=overlap_max,
                alignment_mode=alignment_mode,
                n_alignment_residues_selected=len(alignment_keys),
                n_alignment_ca_aligned=len(shell_ca_1),
                n_binder_ca_compared=min(len(binder_ca_1), len(binder_ca_2)),
            )

        binder_rmsd = calc_rmsd_from_atoms(
            atom_list_1=binder_ca_1,
            atom_list_2=binder_ca_2,
            rot=rot,
            tran=tran,
        )

        return {
            "binder_ca_rmsd_pocket_align": binder_rmsd,
            "n_shell_residues_ref": n_interface_1,
            "n_shell_ca_aligned": len(shell_ca_1),
            "n_binder_ca_compared": len(binder_ca_1),
            "target_shell_cutoff": cutoff,
            "status_target_shell": "ok",
            "error_target_shell": None,
            "n_interface_residues_1": n_interface_1,
            "n_interface_residues_2": n_interface_2,
            "n_shared_interface_residues": len(shared_keys),
            "interface_overlap_method_1": overlap["overlap_method_1"],
            "interface_overlap_method_2": overlap["overlap_method_2"],
            "interface_overlap_max": overlap_max,
            "interface_overlap_threshold": overlap_threshold,
            "alignment_mode": alignment_mode,
            "n_alignment_residues_selected": len(alignment_keys),
            "n_alignment_ca_aligned": len(shell_ca_1),
            "residue_match_mode": residue_match_mode,
        }

    except Exception as e:
        return _failed_result(str(e), cutoff=cutoff)

