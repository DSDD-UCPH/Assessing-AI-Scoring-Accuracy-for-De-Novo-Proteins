"""
This script serves as the core unification component for structural
predictions generated by multiple complex prediction methods. It loads structure
files from different modeling pipelines, extracts standardized metadata from each
individual model, and organizes the predictions into a unified dataset that can be
used for downstream comparative analyses.

The design separates two conceptual layers (this document doing part 2):

1. Single-Structure Extraction
   These operations process one structure file at a time and extract standardized
   metadata describing that prediction.
   - Method parsing: Determine which prediction method produced the structure
     based on directory structure or file paths.
   - Structure loading: Parse .pdb or .cif files using the appropriate Biopython
     parser.
   - Chain identification: Identify the target chain based on its known fixed
     sequence length and determine the corresponding binder chain(s).
   - Sequence extraction: Extract the binder amino acid sequence from the
     structure to provide a consistent identifier across prediction methods.
   - Optional structure features: Extract additional per-structure information
     (e.g., residue contacts or structural metadata) for later analysis.

2. Dataset-Level Unification
   After metadata has been extracted from all individual structures, the dataset
   is aggregated to enable cross-method comparison and filtering.
   - Binder grouping: Group predictions originating from different methods by
     their binder sequence, allowing consistent identification of equivalent
     complexes.
   - Master dataset compilation: Construct a unified dataset (e.g., dataframe or
     record list) containing standardized metadata for all predictions.
   - Smart filtering (future extension): Select representative predictions per
     binder (e.g., highest-ranking prediction) while preserving access to all raw
     predictions.
   - Comparative analysis (future extension): Enable reliable cross-method
     structural comparisons such as binder-binder RMSD and target-target RMSD.

Overall flow:
    -> method parsing
    -> structure loading
    -> chain identification
    -> binder sequence extraction
    -> binder sequence matching
    -> unified dataset compilation
"""

