def build_rank1_method_pairs(
        df: pd.DataFrame,
        binder_col: str = "binder_sequence",
        method_col: str = "method",
        structure_file_col: str = "path",
        rank_col: str = "rank",
        file_type_col: str = "file_type",
        binder_id_col: str = "binder_chain_id",
        target_id_col: str = "target_chain_id",
        keep_cols: list[str] | None = None,
    ) -> pd.DataFrame:
    if keep_cols is None:
        keep_cols = ["score", "score_name"]

    required = [binder_col, method_col, structure_file_col, rank_col, file_type_col, binder_id_col, target_id_col]
    missing = [c for c in required if c not in df.columns]
    if missing:
        raise ValueError(f"Missing required columns: {missing}")
    
    cols_to_use = required + [c for c in keep_cols if c in df.columns]
    work = df[cols_to_use].copy()

    work = work[work[rank_col] == 1].copy()

    work = work.dropna(subset=[binder_col, method_col, structure_file_col, file_type_col, binder_id_col, target_id_col])

    dup_mask = work.duplicated(subset=[binder_col, method_col], keep=False)
    if dup_mask.any():
        dup_df = work.loc[dup_mask, [binder_col, method_col, structure_file_col, file_type_col, binder_id_col, target_id_col]]
        raise ValueError("Found multiple rank-1 rows for the same binder_sequence and method.\n"
                         f"Examples:\n{dup_df.head(10)}")
    
    pair_rows = []

    for binder_seq, group in work.groupby(binder_col, sort=False):
        if len(group) < 2:
            continue

        records = group.to_dict("records")

        for rec1, rec2 in combinations(records, 2):
            row = {
                binder_col: binder_seq,
                "method_1": rec1[method_col],
                "method_2": rec2[method_col],
                "structure_path_1": rec1[structure_file_col],
                "structure_path_2": rec2[structure_file_col],
                "file_type_1": rec1[file_type_col],
                "file_type_2": rec2[file_type_col],
                "binder_chain_1": rec1[binder_id_col],
                "binder_chain_2": rec2[binder_id_col],
                "target_chain_1": rec1[target_id_col],
                "target_chain_2": rec2[target_id_col],
            }

            for c in keep_cols:
                if c in rec1:
                    row[f"{c}_1"] = rec1[c]
                if c in rec2:
                    row[f"{c}_2"] = rec2[c]
            
            pair_rows.append(row)

    pair_df = pd.DataFrame(pair_rows)

    if not pair_df.empty:
        pair_df = pair_df.sort_values(
            by=[binder_col, "method_1", "method_2"]
        ).reset_index(drop=True)

    return pair_df

